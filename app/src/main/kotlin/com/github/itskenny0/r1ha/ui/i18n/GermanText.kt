fun translateGerman(text: String): String {
    germanExact[text]?.let { return it }

    germanRegex.firstNotNullOfOrNull { (regex, replacement) ->
        if (regex.containsMatchIn(text)) regex.replace(text, replacement) else null
    }?.let { return it }

    var translated = text
    germanFragments.forEach { (source, target) -> translated = translated.replace(source, target) }
    return translated
}

